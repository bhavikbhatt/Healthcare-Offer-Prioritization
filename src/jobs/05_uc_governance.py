# MAGIC Applies the governance layer to every asset the journey produced:
# MAGIC
# MAGIC * **Business metadata** — table and column comments (these also ground the Genie Agent).
# MAGIC * **Governed tags** — `Domain` = Healthcare, `medallion_layer`, and `data_classification` = pii on
# MAGIC   member-level tables (all values from the metastore's tag policies), and the governed `phi` tag on member-level columns
# MAGIC   (`member_id` = HIPAA `health_plan_beneficiary_number`). Synthetic data, tagged the way a
# MAGIC   real plan would so policies and audits can key off the tags.
# MAGIC * **Least-privilege grants** — the app's service principal can read the serving
# MAGIC   tables and only *write* to `offer_feedback`; analysts get read access to gold.
# MAGIC * **Audit** — prints the effective grants, tags and model aliases as evidence.

